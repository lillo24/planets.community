"""Extract a pinned official ISTAT workbook into an offline name-only Dart map.

Python 3 standard library only. Run from any directory with the downloaded XLSX
as the single argument. No download, coordinates, provider text or database write.
"""

import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys
import xml.etree.ElementTree as ET
import zipfile


SOURCE_SHA256 = "83842076860450f7e482daecea6b7a769f5f93d0bf5b0d48802b44896d7a26d5"
SOURCE_URL = "https://www.istat.it/storage/codici-unita-amministrative/Elenco-comuni-italiani.xlsx"
SOURCE_DATE = "2026-02-21"
NS = {"s": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}


def normalize(value):
    return re.sub(r"\s+", " ", value.strip()).replace("’", "'").lower()


def extract(path):
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    if digest != SOURCE_SHA256:
        raise ValueError(f"Unreviewed ISTAT workbook SHA-256: {digest}")
    with zipfile.ZipFile(path) as archive:
        strings = [
            "".join(item.itertext())
            for item in ET.fromstring(archive.read("xl/sharedStrings.xml")).findall("s:si", NS)
        ]
        rows = ET.fromstring(archive.read("xl/worksheets/sheet1.xml")).findall("s:sheetData/s:row", NS)
    records = []
    for row in rows:
        cells = {}
        for cell in row:
            value = cell.find("s:v", NS)
            if value is not None:
                text = value.text
                cells[re.sub(r"[0-9]", "", cell.attrib["r"])] = (
                    strings[int(text)] if cell.get("t") == "s" else text
                )
        records.append(cells)
    if records[0].get("G") != "Denominazione in italiano" or len(records) != 7895:
        raise ValueError("Unexpected ISTAT name schema or municipality count")
    names = {}
    ambiguous = set()
    for record in records[1:]:
        if not re.fullmatch(r"[0-9]{6}", record.get("E", "")) or not record.get("G"):
            raise ValueError("Missing official municipality code or Italian name")
        name = record["G"].strip()
        for alias in {record.get("F", ""), name, record.get("H", "")} - {""}:
            key = normalize(alias)
            if key in names and names[key] != name:
                ambiguous.add(key)
            names[key] = name
    for key in ambiguous:
        del names[key]
    if names.get("trento") != "Trento":
        raise ValueError("Required official Trento name missing")
    return names


def dart_string(value):
    return json.dumps(value, ensure_ascii=False).replace("$", r"\$")


def main():
    if len(sys.argv) != 2:
        raise ValueError("Usage: python tool/generate_italian_municipalities.py ISTAT_WORKBOOK.xlsx")
    names = extract(Path(sys.argv[1]))
    output = Path(__file__).resolve().parents[1] / "lib/features/locations/data/italian_municipality_names.g.dart"
    lines = [
        "// GENERATED by tool/generate_italian_municipalities.py; do not edit.",
        "// ISTAT, Elenco dei comuni italiani. CC BY 4.0; names-only adaptation.",
        f"// Source: {SOURCE_URL}",
        f"// Source date: {SOURCE_DATE}; retrieved 2026-10-15.",
        f"// Workbook SHA-256: {SOURCE_SHA256}",
        "// Official Italian, bilingual and other-language names are lookup aliases.",
        "// Ambiguous aliases are omitted. No coordinates or Geoapify data.",
        "const italianMunicipalityNames = <String, String>{",
        *(f"  {dart_string(key)}: {dart_string(value)}," for key, value in sorted(names.items())),
        "};",
        "",
    ]
    output.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    subprocess.run(["dart", "format", str(output)], check=True, shell=sys.platform == "win32")
    print(f"Generated {len(names)} independent name aliases from 7,894 municipalities.")


if __name__ == "__main__":
    main()
